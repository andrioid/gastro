package main_test

import (
	"os"
	"path/filepath"
	"strings"
	"testing"

	"github.com/andrioid/gastro/internal/compiler"
)

// isolatedEnv clears GASTRO_PROJECT so the CLI runs against cmd.Dir even
// when the developer's shell points it at another project.
var isolatedEnv = []string{"GASTRO_PROJECT="}

// writeProject creates a gastro project from relative path → content.
// A go.mod declaring the minimum supported go version is added unless
// files provides one.
func writeProject(t *testing.T, files map[string]string) string {
	t.Helper()
	dir := t.TempDir()
	if _, ok := files["go.mod"]; !ok {
		files["go.mod"] = "module testproject\n\ngo 1.27\n"
	}
	for rel, content := range files {
		path := filepath.Join(dir, rel)
		if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(path, []byte(content), 0o644); err != nil {
			t.Fatal(err)
		}
	}
	return dir
}

// cardProject is a minimal valid project: one page using one component.
func cardProject() map[string]string {
	return map[string]string{
		"components/card.gastro": "---\ntype Props struct { Title string }\nTitle := gastro.Props().Title\n---\n<div>{{ .Title }}</div>\n",
		"pages/index.gastro":     "---\nimport Card \"components/card.gastro\"\n---\n<main>{{ Card (dict \"Title\" \"hi\") }}</main>\n",
	}
}

func TestGenerate_RejectsGoDirectiveBelowMinimum(t *testing.T) {
	t.Parallel()
	files := cardProject()
	files["go.mod"] = "module testproject\n\ngo 1.26\n"
	dir := writeProject(t, files)

	_, stderr, code := runGastroCmd(t, isolatedEnv, dir, "generate")
	if code == 0 {
		t.Fatalf("expected gastro generate to fail for go 1.26; stderr: %s", stderr)
	}
	if !strings.Contains(stderr, "go 1.26") || !strings.Contains(stderr, "requires go 1.27") {
		t.Errorf("stderr should name the declared and the required version; got: %s", stderr)
	}
}

func TestCheck_FreshGenerationIsUpToDate(t *testing.T) {
	t.Parallel()
	dir := writeProject(t, cardProject())

	if _, stderr, code := runGastroCmd(t, isolatedEnv, dir, "generate"); code != 0 {
		t.Fatalf("generate failed (%d): %s", code, stderr)
	}
	if _, stderr, code := runGastroCmd(t, isolatedEnv, dir, "check"); code != 0 {
		t.Fatalf("check right after generate should pass, got exit %d: %s", code, stderr)
	}
}

func TestCheck_VersionMismatchIsStale(t *testing.T) {
	t.Parallel()
	dir := writeProject(t, cardProject())
	// A tree produced by a different gastro release.
	if _, err := compiler.Compile(dir, filepath.Join(dir, ".gastro"), compiler.CompileOptions{Version: "v0.0.1"}); err != nil {
		t.Fatalf("compile: %v", err)
	}

	_, stderr, code := runGastroCmd(t, isolatedEnv, dir, "check")
	if code != 1 {
		t.Fatalf("expected exit 1 (stale), got %d: %s", code, stderr)
	}
	if !strings.Contains(stderr, "generated by gastro v0.0.1") {
		t.Errorf("stderr should name the version the tree was generated by; got: %s", stderr)
	}
}
