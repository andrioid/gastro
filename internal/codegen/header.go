package codegen

import (
	"strings"

	"github.com/andrioid/gastro/internal/buildinfo"
)

const (
	headerPrefix = "// Code generated by gastro "
	headerSuffix = ". DO NOT EDIT."
)

// GeneratedHeader returns the first line of every generated Go file,
// stamped with the gastro version that produced it. An empty version
// stamps the running binary's version (see buildinfo.Version).
func GeneratedHeader(version string) string {
	if version == "" {
		version = buildinfo.Version()
	}
	return headerPrefix + version + headerSuffix
}

// ParseGeneratedHeader extracts the version stamp from a generated file's
// first line. ok is false when the line is not a version-stamped gastro
// header, including the unstamped header written before v0.4.0.
func ParseGeneratedHeader(line string) (version string, ok bool) {
	rest, found := strings.CutPrefix(line, headerPrefix)
	if !found {
		return "", false
	}
	version, found = strings.CutSuffix(rest, headerSuffix)
	if !found || version == "" || strings.ContainsAny(version, " \t") {
		return "", false
	}
	return version, true
}
