package compiler_test

import (
	"bytes"
	"io/fs"
	"os"
	"path/filepath"
	"strings"
	"testing"

	"github.com/andrioid/gastro/internal/compiler"
)

// readTree returns every regular file under root keyed by its
// slash-separated path relative to root.
func readTree(t *testing.T, root string) map[string][]byte {
	t.Helper()
	files := map[string][]byte{}
	err := filepath.WalkDir(root, func(path string, d fs.DirEntry, err error) error {
		if err != nil || d.IsDir() {
			return err
		}
		rel, err := filepath.Rel(root, path)
		if err != nil {
			return err
		}
		data, err := os.ReadFile(path)
		if err != nil {
			return err
		}
		files[filepath.ToSlash(rel)] = data
		return nil
	})
	if err != nil {
		t.Fatalf("walking %s: %v", root, err)
	}
	return files
}

func TestCompile_StampsVersionInEveryGoFileHeader(t *testing.T) {
	outputDir := t.TempDir()
	if _, err := compiler.Compile(filepath.Join("testdata", "basic"), outputDir, compiler.CompileOptions{Version: "v9.8.7"}); err != nil {
		t.Fatalf("compile: %v", err)
	}

	const want = "// Code generated by gastro v9.8.7. DO NOT EDIT."
	goFiles := 0
	for path, data := range readTree(t, outputDir) {
		if !strings.HasSuffix(path, ".go") {
			continue
		}
		goFiles++
		first, _, _ := strings.Cut(string(data), "\n")
		if first != want {
			t.Errorf("%s: header = %q, want %q", path, first, want)
		}
	}
	if goFiles == 0 {
		t.Fatal("no generated .go files found")
	}
}

func TestCompile_DifferentVersionsDifferOnlyInHeader(t *testing.T) {
	projectDir := filepath.Join("testdata", "basic")
	a, b := t.TempDir(), t.TempDir()
	if _, err := compiler.Compile(projectDir, a, compiler.CompileOptions{Version: "v0.4.0"}); err != nil {
		t.Fatalf("compile a: %v", err)
	}
	if _, err := compiler.Compile(projectDir, b, compiler.CompileOptions{Version: "v0.4.1"}); err != nil {
		t.Fatalf("compile b: %v", err)
	}

	treeA, treeB := readTree(t, a), readTree(t, b)
	if len(treeA) != len(treeB) {
		t.Fatalf("trees differ in file count: %d vs %d", len(treeA), len(treeB))
	}
	for path, dataA := range treeA {
		dataB, ok := treeB[path]
		if !ok {
			t.Errorf("%s missing from second generation", path)
			continue
		}
		linesA := bytes.Split(dataA, []byte("\n"))
		linesB := bytes.Split(dataB, []byte("\n"))
		if len(linesA) != len(linesB) {
			t.Errorf("%s: line counts differ (%d vs %d)", path, len(linesA), len(linesB))
			continue
		}
		for i := range linesA {
			if bytes.Equal(linesA[i], linesB[i]) {
				continue
			}
			if i != 0 {
				t.Errorf("%s:%d differs outside the header: %q vs %q", path, i+1, linesA[i], linesB[i])
			}
		}
	}
}

func TestGeneratedVersion_ReadsStampFromTree(t *testing.T) {
	outputDir := t.TempDir()
	if _, err := compiler.Compile(filepath.Join("testdata", "basic"), outputDir, compiler.CompileOptions{Version: "v0.4.2"}); err != nil {
		t.Fatalf("compile: %v", err)
	}
	got, err := compiler.GeneratedVersion(outputDir)
	if err != nil {
		t.Fatalf("GeneratedVersion: %v", err)
	}
	if got != "v0.4.2" {
		t.Errorf("GeneratedVersion = %q, want v0.4.2", got)
	}
}

func TestGeneratedVersion_UnstampedTreeReportsEmpty(t *testing.T) {
	outputDir := t.TempDir()
	if err := os.WriteFile(filepath.Join(outputDir, "routes.go"), []byte("// Code generated by gastro. DO NOT EDIT.\npackage gastro\n"), 0o644); err != nil {
		t.Fatal(err)
	}
	got, err := compiler.GeneratedVersion(outputDir)
	if err != nil {
		t.Fatalf("GeneratedVersion: %v", err)
	}
	if got != "" {
		t.Errorf("GeneratedVersion = %q, want empty for a pre-stamp tree", got)
	}
}
